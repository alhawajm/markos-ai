import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const css = fs.readFileSync(path.join(root, "apps/web/app/theme-tokens.css"), "utf8");
const blocks = css.split("}");
const parse = (block) => Object.fromEntries([...block.matchAll(/--([\w-]+):\s*(#[\da-fA-F]{6}(?:[\da-fA-F]{2})?|var\(--[\w-]+\));/g)].map((m) => [m[1], m[2]]));
const resolveColors = (tokens) => {
  const resolve = (name, visited = new Set()) => {
    if (visited.has(name) || !tokens[name]) throw new Error(`Invalid color token: ${name}`);
    const reference = /^var\(--([\w-]+)\)$/.exec(tokens[name]);
    return reference ? resolve(reference[1], new Set([...visited, name])) : tokens[name];
  };
  return Object.fromEntries(Object.keys(tokens).map((name) => [name, resolve(name)]));
};
const lightTokens = parse(blocks[0]);
const light = resolveColors(lightTokens);
const dark = resolveColors({ ...lightTokens, ...parse(blocks[1]) });
if (!light.primary || !dark.primary || light.background === dark.background) throw new Error("Could not read both MARKOS themes");
const mix = (a, b, amount) =>
  "#" +
  [1, 3, 5]
    .map((i) =>
      Math.round(parseInt(a.slice(i, i + 2), 16) * amount + parseInt(b.slice(i, i + 2), 16) * (1 - amount))
        .toString(16)
        .padStart(2, "0")
    )
    .join("");
for (const colors of [light, dark]) {
  for (const [name, amount] of [
    ["primary", 0.15],
    ["secondary", 0.2],
    ["accent", 0.12],
    ["supporting", 0.2],
    ["highlight", 0.15],
    ["success", 0.1],
    ["warning", 0.1],
    ["danger", 0.1]
  ]) {
    colors[`${name}-soft`] = mix(colors[name], colors.surface, amount);
  }
}
const camel = (theme) => Object.fromEntries(Object.entries(theme).map(([key, value]) => [key.replace(/-([a-z])/g, (_, c) => c.toUpperCase()), value]));
const output = `// Generated by scripts/generate-native-tokens.mjs from the authoritative web palette.\n// Regenerate after changing apps/web/app/theme-tokens.css. Do not edit color values here.\nexport const nativeColors = ${JSON.stringify({ light: camel(light), dark: camel(dark) }, null, 2)} as const;\n\nexport type NativeColors = { [K in keyof typeof nativeColors.light]: string };\nexport const nativeRadii = { button: 12, input: 12, card: 16, sheet: 24, pill: 999 } as const;\nexport const nativeLayout = { gutter: 20, controlHeight: 48, navigationIcon: 24, actionIcon: 20 } as const;\n`;
const target = path.join(root, "packages/ui-tokens/src/native.ts");
const formattedOutput = await format(output, { ...(await resolveConfig(target)), filepath: target });
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== formattedOutput) throw new Error("Native colors are stale. Run node scripts/generate-native-tokens.mjs");
} else fs.writeFileSync(target, formattedOutput);
console.log("Native tokens match the MARKOS light and dark palette.");
